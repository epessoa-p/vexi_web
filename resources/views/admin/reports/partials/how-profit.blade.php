    <summary>¿Cómo se calcula?</summary>
    <p><strong>Ingresos</strong> es el dinero que entró por cobros, menos los reembolsos; lo que quedó a crédito cuenta cuando se cobra.</p>
    <p><strong>Costo de productos</strong> son las unidades vendidas al precio de compra que hoy tiene cada producto, descontando devoluciones.</p>
    <p>Las compras a proveedores no se restan: ese dinero sigue en tu estantería hasta que el producto se vende. Es una estimación para orientarte, no un balance contable.</p>
